import Foundation
import Observation

public enum ClipKind: String, Codable, Sendable { case text, url, image }

public struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    public var id = UUID()
    public var kind: ClipKind
    public var text: String?
    public var imageFile: String?
    public var sourceBundleID: String?
    public var copiedAt: Date
    public var pinned = false
}

public struct PasteboardSnapshot: Sendable {
    public var changeCount: Int
    public var types: [String]
    public var text: String?
    public var imageData: Data?
    public var sourceBundleID: String?
    /// The app that was in front until moments ago: a copy made just before switching apps may belong to it.
    public var previousBundleID: String?
    public init(changeCount: Int, types: [String] = [], text: String? = nil, imageData: Data? = nil, sourceBundleID: String? = nil,
                previousBundleID: String? = nil) {
        self.changeCount = changeCount; self.types = types; self.text = text; self.imageData = imageData; self.sourceBundleID = sourceBundleID
        self.previousBundleID = previousBundleID
    }
}

@MainActor
public protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    func snapshot() -> PasteboardSnapshot
    func write(text: String)
    func write(imageData: Data)
    func clear()
    /// Sends ⌘V to the app in front. False when that is not allowed (no Accessibility).
    func paste() -> Bool
}

public enum LinkCleaner {
    static let exact: Set<String> = ["fbclid", "gclid", "dclid", "msclkid", "mc_eid", "mc_cid", "igshid", "yclid", "twclid", "_hsenc", "_hsmi", "ref_src", "ref_url", "spm"]

    /// A single web link, or nil.
    public static func url(_ s: String) -> URLComponents? {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(where: \.isWhitespace), let c = URLComponents(string: t), ["http", "https"].contains(c.scheme?.lowercased() ?? ""), c.host != nil else { return nil }
        return c
    }

    public static func clean(_ s: String) -> String {
        guard var c = url(s) else { return s }
        let kept = c.queryItems?.filter { !($0.name.lowercased().hasPrefix("utm_") || exact.contains($0.name.lowercased())) }
        c.queryItems = (kept?.isEmpty ?? true) ? nil : kept
        return c.string ?? s
    }
}

/// Never stored: anything a password manager or app marked as secret, temporary or machine-made.
public let sensitivePasteboardTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

@MainActor @Observable
public final class ClipboardHistory: Tool {
    public static let maxUnpinned = 200, maxTextLength = 100_000, maxImageBytes = 10_000_000
    public private(set) var items: [ClipItem] = []
    public private(set) var status: String?
    public private(set) var lastDeleted: [ClipItem] = []
    public private(set) var excluded: Set<String>
    public private(set) var retentionDays: Int
    public private(set) var cleanLinks: Bool
    public private(set) var autoClear: Bool
    @ObservationIgnored private let pasteboard: PasteboardAccess
    @ObservationIgnored private let folder: URL
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private let now: () -> Date
    @ObservationIgnored private let sleep: @Sendable (TimeInterval) async throws -> Void
    @ObservationIgnored private var lastSeen: Int
    @ObservationIgnored private var poll: Task<Void, Never>?
    @ObservationIgnored private var clearTask: Task<Void, Never>?
    @ObservationIgnored private var undoExpiry: Task<Void, Never>?

    public init(pasteboard: PasteboardAccess, folder: URL, defaults: UserDefaults = .standard, now: @escaping () -> Date = Date.init,
                sleep: @escaping @Sendable (TimeInterval) async throws -> Void = { try await Task.sleep(for: .seconds($0)) }) {
        self.pasteboard = pasteboard; self.folder = folder; self.defaults = defaults; self.now = now; self.sleep = sleep
        lastSeen = pasteboard.changeCount
        excluded = Set(defaults.stringArray(forKey: "clipboard.excluded") ?? [])
        retentionDays = defaults.object(forKey: "clipboard.retentionDays") as? Int ?? 7
        cleanLinks = defaults.bool(forKey: "clipboard.cleanLinks")
        autoClear = defaults.bool(forKey: "clipboard.autoClear")
        if let d = try? Data(contentsOf: folder.appendingPathComponent("history.json")) { items = (try? JSONDecoder().decode([ClipItem].self, from: d)) ?? [] }
    }

    // MARK: Tool: the poll exists only while the tool is on
    public func start() {
        lastSeen = pasteboard.changeCount
        prune()
        poll = Task { [weak self, sleep] in
            while !Task.isCancelled {
                do { try await sleep(0.5) } catch { return }
                self?.check()
            }
        }
    }

    public func stop() { poll?.cancel(); poll = nil; clearTask?.cancel(); clearTask = nil; discardUndo() }

    public var isPolling: Bool { poll != nil }

    // MARK: Watching
    public func check() {
        guard pasteboard.changeCount != lastSeen else { return }
        let snap = pasteboard.snapshot()
        lastSeen = snap.changeCount
        scheduleAutoClear()
        ingest(snap)
    }

    private func ingest(_ s: PasteboardSnapshot) {
        guard sensitivePasteboardTypes.isDisjoint(with: s.types) else { return }
        for src in [s.sourceBundleID, s.previousBundleID] { if let src, excluded.contains(src) { return } }
        var item: ClipItem
        if let raw = s.text?.trimmingCharacters(in: .whitespacesAndNewlines), !raw.isEmpty {
            guard raw.count <= Self.maxTextLength else { return }
            var text = raw
            if cleanLinks, LinkCleaner.url(raw) != nil {
                let cleaned = LinkCleaner.clean(raw)
                if cleaned != raw { text = cleaned; pasteboard.write(text: cleaned); lastSeen = pasteboard.changeCount }
            }
            item = ClipItem(kind: LinkCleaner.url(text) != nil ? .url : .text, text: text, sourceBundleID: s.sourceBundleID, copiedAt: now())
            if let i = items.firstIndex(where: { $0.text == text }) { item.pinned = items[i].pinned; items.remove(at: i) }
        } else if let data = s.imageData, data.count <= Self.maxImageBytes {
            let name = UUID().uuidString + ".png"
            try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            guard (try? data.write(to: folder.appendingPathComponent(name))) != nil else { return }
            item = ClipItem(kind: .image, imageFile: name, sourceBundleID: s.sourceBundleID, copiedAt: now())
        } else { return }
        items.insert(item, at: 0)
        prune()
    }

    private func scheduleAutoClear() {
        clearTask?.cancel(); clearTask = nil
        guard autoClear else { return }
        let seen = lastSeen
        clearTask = Task { [weak self, sleep] in
            do { try await sleep(60) } catch { return }
            guard let self, self.pasteboard.changeCount == seen else { return } // the user copied something newer
            self.pasteboard.clear(); self.lastSeen = self.pasteboard.changeCount
        }
    }

    /// Called when the screen locks.
    public func screenLocked() {
        guard autoClear, isPolling else { return }
        pasteboard.clear(); lastSeen = pasteboard.changeCount
    }

    // MARK: Actions
    public func search(_ q: String) -> [ClipItem] {
        let t = q.trimmingCharacters(in: .whitespaces)
        let all = items.sorted { ($0.pinned ? 1 : 0, $0.copiedAt) > ($1.pinned ? 1 : 0, $1.copiedAt) }
        return t.isEmpty ? all : all.filter { $0.text?.localizedCaseInsensitiveContains(t) ?? false }
    }

    public func imageURL(_ item: ClipItem) -> URL? { item.imageFile.map { folder.appendingPathComponent($0) } }

    /// Puts the item on the clipboard and pastes it. `plain` drops formatting by writing text only.
    @discardableResult
    public func paste(_ item: ClipItem, andSend: Bool = true) -> Bool {
        switch item.kind {
        case .text, .url: pasteboard.write(text: item.text ?? "")
        case .image: if let u = imageURL(item), let d = try? Data(contentsOf: u) { pasteboard.write(imageData: d) }
        }
        lastSeen = pasteboard.changeCount
        guard andSend else { status = "Copied."; return true }
        let sent = pasteboard.paste()
        status = sent ? nil : "Copied. Press ⌘V to paste (Accessibility is off)."
        return sent
    }

    /// Whatever is on the clipboard now, as plain text.
    @discardableResult
    public func pastePlainCurrent() -> Bool {
        guard let text = pasteboard.snapshot().text, !text.isEmpty else { return false }
        pasteboard.write(text: text); lastSeen = pasteboard.changeCount
        return pasteboard.paste()
    }

    public func togglePin(_ item: ClipItem) { if let i = items.firstIndex(of: item) { items[i].pinned.toggle(); save() } }

    public func delete(_ item: ClipItem) { removing([item]) }
    public func clearAll(keepPinned: Bool = true) { removing(items.filter { !(keepPinned && $0.pinned) }) }

    private func removing(_ gone: [ClipItem]) {
        guard !gone.isEmpty else { return }
        items.removeAll { i in gone.contains { $0.id == i.id } }
        lastDeleted = gone // image files stay until the next prune so Undo can bring them back
        save()
        // The undo window ends by itself so a deleted screenshot does not stay on disk for days.
        undoExpiry?.cancel()
        undoExpiry = Task { [weak self, sleep] in
            do { try await sleep(10) } catch { return }
            guard let self, self.lastDeleted.map(\.id) == gone.map(\.id) else { return }
            self.discardUndo()
        }
    }

    /// Forget what could be undone and delete the screenshot files of removed items now.
    public func discardUndo() { lastDeleted = []; prune() }

    public func undoDelete() { items += lastDeleted; items.sort { $0.copiedAt > $1.copiedAt }; lastDeleted = []; save() }

    public func neverStore(from bundleID: String) {
        excluded.insert(bundleID); defaults.set(Array(excluded), forKey: "clipboard.excluded")
        removing(items.filter { $0.sourceBundleID == bundleID && !$0.pinned })
    }
    public func allowAgain(_ bundleID: String) { excluded.remove(bundleID); defaults.set(Array(excluded), forKey: "clipboard.excluded") }
    public func setRetention(_ days: Int) { retentionDays = min(max(days, 1), 90); defaults.set(retentionDays, forKey: "clipboard.retentionDays"); prune() }
    public func setCleanLinks(_ on: Bool) { cleanLinks = on; defaults.set(on, forKey: "clipboard.cleanLinks") }
    public func setAutoClear(_ on: Bool) { autoClear = on; defaults.set(on, forKey: "clipboard.autoClear"); if !on { clearTask?.cancel() } }

    /// Old items go, pinned stay; images of removed items are deleted from disk.
    private func prune() {
        let cutoff = now().addingTimeInterval(-Double(retentionDays) * 86_400)
        var kept: [ClipItem] = [], unpinned = 0
        for i in items.sorted(by: { $0.copiedAt > $1.copiedAt }) {
            if i.pinned { kept.append(i); continue }
            unpinned += 1
            if i.copiedAt >= cutoff && unpinned <= Self.maxUnpinned { kept.append(i) }
        }
        let live = Set(kept.compactMap(\.imageFile)), undoable = Set(lastDeleted.compactMap(\.imageFile))
        let files = (try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? []
        for f in files where f.hasSuffix(".png") && !live.contains(f) && !undoable.contains(f) { try? FileManager.default.removeItem(at: folder.appendingPathComponent(f)) }
        items = kept
        save()
    }

    private func save() {
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? JSONEncoder().encode(items).write(to: folder.appendingPathComponent("history.json"), options: .atomic)
    }
}
