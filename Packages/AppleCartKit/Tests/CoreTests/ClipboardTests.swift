import Foundation
import Testing
@testable import Core

@MainActor
private final class FakeBoard: PasteboardAccess {
    var changeCount = 1
    var text: String?, image: Data?, types: [String] = [], source: String?, previous: String?
    var pastes = 0, canPaste = true, cleared = 0
    func snapshot() -> PasteboardSnapshot { .init(changeCount: changeCount, types: types, text: text, imageData: image, sourceBundleID: source, previousBundleID: previous) }
    func write(text: String) { self.text = text; image = nil; types = []; changeCount += 1 }
    func write(imageData: Data) { image = imageData; text = nil; changeCount += 1 }
    func clear() { text = nil; image = nil; cleared += 1; changeCount += 1 }
    func paste() -> Bool { pastes += 1; return canPaste }
    /// What another app does.
    func copy(_ t: String, types: [String] = [], from: String? = nil) { text = t; image = nil; self.types = types; source = from; changeCount += 1 }
}

private final class Clock: @unchecked Sendable { var t = Date(timeIntervalSince1970: 2_000_000) }

@MainActor
private func make(_ b: FakeBoard, clock: Clock = Clock(), sleep: @escaping @Sendable (TimeInterval) async throws -> Void = { _ in try await Task.sleep(for: .seconds(3600)) }) -> (ClipboardHistory, URL, UserDefaults) {
    let dir = FileManager.default.temporaryDirectory.appendingPathComponent("clip-" + UUID().uuidString)
    let d = UserDefaults(suiteName: "clip-" + UUID().uuidString)!
    return (ClipboardHistory(pasteboard: b, folder: dir, defaults: d, now: { clock.t }, sleep: sleep), dir, d)
}

@MainActor
@Suite struct ClipboardTests {
    @Test func storesTextAndLinksNewestFirstAndDedupes() {
        let b = FakeBoard(); let (h, _, _) = make(b)
        b.copy("hello"); h.check(); b.copy("https://a.example/x"); h.check(); b.copy("hello"); h.check()
        #expect(h.items.map(\.text) == ["hello", "https://a.example/x"] && h.items[1].kind == .url)
    }

    @Test func concealedTransientAndAutoGeneratedItemsAreNeverStored() {
        let b = FakeBoard(); let (h, _, _) = make(b)
        for t in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            b.copy("secret-\(t)", types: ["public.utf8-plain-text", t]); h.check()
        }
        #expect(h.items.isEmpty)
        b.copy("fine", types: ["public.utf8-plain-text"]); h.check()
        #expect(h.items.count == 1)
    }

    @Test func excludedAppsAreSkippedAndNeverStoreRemovesExisting() {
        let b = FakeBoard(); let (h, _, d) = make(b)
        b.copy("a", from: "com.bank"); h.check(); b.copy("b", from: "com.ok"); h.check()
        h.neverStore(from: "com.bank")
        #expect(h.items.map(\.text) == ["b"])
        b.copy("c", from: "com.bank"); h.check()
        #expect(h.items.count == 1)
        #expect(Set(d.stringArray(forKey: "clipboard.excluded") ?? []) == ["com.bank"])
        // Copied in the bank app, then switched to the browser before the next poll.
        b.previous = "com.bank"; b.copy("d", from: "com.browser"); h.check()
        #expect(h.items.count == 1)
    }

    @Test func retentionDropsOldItemsButPinnedStayAndEverythingPersists() {
        let b = FakeBoard(); let clock = Clock(); let (h, dir, d) = make(b, clock: clock)
        b.copy("old"); h.check(); b.copy("pinned"); h.check()
        h.togglePin(h.items.first { $0.text == "pinned" }!)
        clock.t += 8 * 86_400
        b.copy("new"); h.check()
        #expect(Set(h.items.compactMap(\.text)) == ["pinned", "new"])
        let again = ClipboardHistory(pasteboard: b, folder: dir, defaults: d, now: { clock.t })
        #expect(Set(again.items.compactMap(\.text)) == ["pinned", "new"])
    }

    @Test func searchFindsTextAndPinnedComeFirst() {
        let b = FakeBoard(); let (h, _, _) = make(b)
        for t in ["alpha one", "beta two", "alpha three"] { b.copy(t); h.check() }
        h.togglePin(h.items.first { $0.text == "alpha one" }!)
        #expect(h.search("ALPHA").map(\.text) == ["alpha one", "alpha three"])
        #expect(h.search("").first?.text == "alpha one")
    }

    @Test func imagesAreFilesAndTheirFilesGoWhenPruned() throws {
        let b = FakeBoard(); let clock = Clock(); let (h, dir, _) = make(b, clock: clock)
        b.image = Data(repeating: 7, count: 100); b.text = nil; b.changeCount += 1; h.check()
        let f = try #require(h.items.first?.imageFile)
        #expect(FileManager.default.fileExists(atPath: dir.appendingPathComponent(f).path))
        clock.t += 9 * 86_400; h.setRetention(7)
        #expect(h.items.isEmpty && !FileManager.default.fileExists(atPath: dir.appendingPathComponent(f).path))
    }

    @Test func deleteCanBeUndone() {
        let b = FakeBoard(); let (h, _, _) = make(b)
        b.copy("x"); h.check(); h.delete(h.items[0])
        #expect(h.items.isEmpty)
        h.undoDelete()
        #expect(h.items.count == 1)
    }

    @Test func deletedScreenshotLeavesDiskWhenUndoEndsOrToolStops() async throws {
        let b = FakeBoard(); let (h, dir, _) = make(b, sleep: { _ in })
        b.image = Data(repeating: 7, count: 100); b.changeCount += 1; h.check()
        let f = dir.appendingPathComponent(try #require(h.items.first?.imageFile)).path
        h.delete(h.items[0])
        #expect(FileManager.default.fileExists(atPath: f)) // Undo can still bring it back
        try await Task.sleep(for: .milliseconds(100))
        #expect(h.lastDeleted.isEmpty && !FileManager.default.fileExists(atPath: f))

        let b2 = FakeBoard(); let (h2, dir2, _) = make(b2) // undo window never ends by itself here
        b2.image = Data(repeating: 7, count: 100); b2.changeCount += 1; h2.check()
        let f2 = dir2.appendingPathComponent(try #require(h2.items.first?.imageFile)).path
        h2.delete(h2.items[0]); h2.stop()
        #expect(h2.lastDeleted.isEmpty && !FileManager.default.fileExists(atPath: f2))
    }

    @Test func linkCleanerRemovesTrackingOnly() {
        #expect(LinkCleaner.clean("https://a.com/p?id=3&utm_source=x&fbclid=abc") == "https://a.com/p?id=3")
        #expect(LinkCleaner.clean("https://a.com/p?utm_medium=y") == "https://a.com/p")
        #expect(LinkCleaner.clean("not a link utm_source=1") == "not a link utm_source=1")
        #expect(LinkCleaner.clean("https://a.com/?q=swift") == "https://a.com/?q=swift")
    }

    @Test func cleanLinksRewritesTheClipboardOnceWhenOn() {
        let b = FakeBoard(); let (h, _, _) = make(b)
        b.copy("https://a.com/p?utm_source=x"); h.check()
        #expect(h.items[0].text == "https://a.com/p?utm_source=x" && b.text == "https://a.com/p?utm_source=x")
        h.setCleanLinks(true)
        b.copy("https://b.com/p?gclid=1"); h.check()
        #expect(b.text == "https://b.com/p" && h.items[0].text == "https://b.com/p")
        h.check(); #expect(h.items.count == 2)
    }

    @Test func autoClearEmptiesTheClipboardOnlyIfNothingNewWasCopied() async throws {
        let b = FakeBoard(); let (h, _, _) = make(b, sleep: { _ in })
        h.setAutoClear(true)
        b.copy("secret", types: ["org.nspasteboard.ConcealedType"]); h.check()
        try await Task.sleep(for: .milliseconds(100))
        #expect(b.cleared == 1 && h.items.isEmpty)
        let b2 = FakeBoard(); let (h2, _, _) = make(b2, sleep: { _ in try await Task.sleep(for: .milliseconds(50)) })
        h2.setAutoClear(true)
        b2.copy("one"); h2.check(); b2.copy("two") // copied again before the timer ends
        try await Task.sleep(for: .milliseconds(200))
        #expect(b2.cleared == 0)
        // Screen lock clears only while the tool is on.
        let b3 = FakeBoard(); let (h3, _, _) = make(b3)
        h3.setAutoClear(true)
        h3.screenLocked(); #expect(b3.cleared == 0)
        h3.start(); h3.screenLocked(); #expect(b3.cleared == 1); h3.stop()
    }

    @Test func pollRunsOnlyWhileOnAndPasteReportsMissingAccessibility() {
        let b = FakeBoard(); let (h, _, _) = make(b)
        #expect(!h.isPolling); h.start(); #expect(h.isPolling); h.stop(); #expect(!h.isPolling)
        b.copy("x"); h.check()
        b.canPaste = false
        #expect(!h.paste(h.items[0]) && h.status?.contains("Accessibility") == true)
        b.copy("<b>rich</b>"); #expect(h.pastePlainCurrent() == false && b.text == "<b>rich</b>")
    }

    @Test func copyingAnItemNeverSendsAPaste() {
        let b = FakeBoard(); let (h, _, _) = make(b)
        b.copy("first"); h.check(); b.copy("second"); h.check()
        let first = h.items.first { $0.text == "first" }!
        #expect(h.paste(first, andSend: false))
        #expect(b.text == "first" && b.pastes == 0 && h.status == "Copied.")
    }
}
